/**
 * Compact builder. Every row is a DRAFT (`published: false`) until Megz reviews
 * the Arabic. "System" column text must stay within what the product does:
 * dress calendar that rejects overlapping reservations, deposits and payments,
 * printable receipts, reservation statuses (reserved/picked up/returned/
 * cancelled), availability by date, branches, staff permissions.
 */
function p(
  slug: string,
  h1: string,
  description: string,
  intro: string,
  steps: S[],
  cmp: C[],
  faq: F[],
  related: string[],
): PseoRow {
  return {
    family: "hulul",
    slug,
    h1,
    title: `${h1} | Gateling Atelier`,
    description,
    intro,
    sections: [
      {
        h2: "الخطوات",
        steps: steps.map(([title, body]) => ({ title, body })),
      },
    ],
    comparison: cmp.map(([aspect, manual, system]) => ({
      aspect,
      manual,
      system,
    })),
    faq: faq.map(([q, a]) => ({ q, a })),
    related: related.map((s) => ({ family: "hulul" as const, slug: s })),
    published: false,
    updatedAt: "2026-11-18",
  };
}

